#!/usr/bin/env python3
"""Checks the language profiles in data/profiles/ and writes the Chrome extension's copy of them.

data/profiles/<language>.json is the single source (the field list is in data/profiles/README.md); the hook and
exports read it directly, and the extension, which can't read files outside its folder, imports the generated
extension/src/profile-data.js. Tests fail while that copy differs from the profiles.
Usage: python3 scripts/make_profiles.py [--check]   (--check: fail if a profile is malformed or the copy is stale)
"""
import argparse
import json
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
import fwlib  # noqa: E402

OUT = fwlib.PLUGIN_ROOT / 'extension' / 'src' / 'profile-data.js'
GENERIC = '_generic'
CHOICES = {('script', 'direction'): ('ltr', 'rtl'), ('script', 'hint'): ('sound', 'romanization'),
           ('script', 'reading', 'early'): ('none', 'romaji', 'kana'),
           ('script', 'reading', 'late'): ('none', 'romaji', 'kana'), ('script', 'reading', 'late_only_with'): ('', 'kanji')}


def load(directory=None):
    """{file stem: parsed profile} for every profile, the generic one included."""
    return {path.stem: json.loads(path.read_text(encoding='utf-8'))
            for path in sorted(Path(directory or fwlib.PROFILE_DIR).glob('*.json'))}


def is_pair(value):
    return isinstance(value, list) and len(value) == 2 and all(isinstance(v, str) and v for v in value)


def problems(data, generic, path=()):
    """What is wrong with a profile: fields the generic profile doesn't have, wrong types, bad values."""
    out = []
    for key, value in data.items():
        where = '.'.join(path + (key,))
        if key not in generic:
            out.append(f'{where}: unknown field')
            continue
        base = generic[key]
        if isinstance(base, dict) and key not in ('not_followed_by', 'level_examples', 'synonyms'):
            out += problems(value, base, path + (key,)) if isinstance(value, dict) else [f'{where}: must be an object']
        elif base is not None and type(value) is not type(base):
            out.append(f'{where}: must be {type(base).__name__}, not {type(value).__name__}')
        elif (path + (key,)) in CHOICES and value not in CHOICES[path + (key,)]:
            out.append(f'{where}: must be one of {", ".join(CHOICES[path + (key,)])}')
    if path:
        return out
    examples, extension = data.get('examples') or {}, data.get('extension') or {}
    pairs = list(examples.get('default_swaps') or []) + [p for v in (extension.get('level_examples') or {}).values() for p in v]
    pairs += [p for p in (extension.get('filler_example'), extension.get('adjective_example')) if p is not None]
    out += [f'not an [English, word] pair: {p!r}' for p in pairs if not is_pair(p)]
    gloss = examples.get('gloss')
    if gloss is not None and not (isinstance(gloss, dict) and all(isinstance(gloss.get(k), str) and gloss[k] for k in ('word', 'en', 'hint'))):
        out.append('examples.gloss: needs word, en and hint')
    for item in extension.get('synonym_examples') or []:
        if not (isinstance(item, list) and len(item) == 2 and isinstance(item[1], str) and isinstance(item[0], list)
                and item[0] and all(isinstance(e, str) for e in item[0])):
            out.append(f'extension.synonym_examples: not [[English, ...], word]: {item!r}')
    if set(extension.get('level_examples') or {}) - {'1', '2'}:
        out.append('extension.level_examples: keys are levels "1" and "2"')
    for key, value in (extension.get('synonyms') or {}).items():
        if not (isinstance(value, list) and all(isinstance(v, str) for v in value)):
            out.append(f'extension.synonyms.{key}: must be a list of English words')
    for key, value in ((data.get('exposure') or {}).get('not_followed_by') or {}).items():
        if not isinstance(value, str):
            out.append(f'exposure.not_followed_by.{key}: must be a regex string')
    return out


def render(profiles):
    generic = profiles[GENERIC]
    others = {name: data for name, data in profiles.items() if name != GENERIC}
    dump = lambda data: json.dumps(data, ensure_ascii=False, indent=2)
    return ('// Generated by scripts/make_profiles.py from data/profiles/*.json: do not edit by hand. After changing a\n'
            '// profile, run python3 scripts/make_profiles.py (tests fail while this copy differs from the profiles).\n'
            f'export const GENERIC = {dump(generic)};\n\n'
            f'export const PROFILES = {dump(others)};\n')


def check(directory=None, out=OUT):
    """Problems with the profiles and the extension's copy, as a list of strings (empty when all is well)."""
    profiles = load(directory)
    found = [] if GENERIC in profiles else [f'{GENERIC}.json is missing']
    for name, data in profiles.items():
        if name == GENERIC:
            continue
        found += [f'{name}.json: {p}' for p in problems(data, profiles.get(GENERIC, {}))]
        if str(data.get('language', '')).strip().lower() != name:
            found.append(f'{name}.json: "language" must be the file name with a capital, like "{name.title()}"')
    if not found and (not Path(out).exists() or Path(out).read_text(encoding='utf-8') != render(profiles)):
        found.append(f'{Path(out).name} is out of date; run python3 scripts/make_profiles.py')
    return found


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    if args.check:
        found = check()
        if found:
            sys.exit('\n'.join(found))
        print(f'{len(load()) - 1} language profiles OK; {OUT.name} is current')
        return
    profiles = load()
    found = [f'{name}.json: {p}' for name, data in profiles.items() if name != GENERIC
             for p in problems(data, profiles[GENERIC])]
    if found:
        sys.exit('\n'.join(found))
    OUT.write_text(render(profiles), encoding='utf-8')
    print(f'wrote {OUT} ({len(profiles) - 1} languages)')


if __name__ == '__main__':
    main()
